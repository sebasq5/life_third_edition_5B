function getExamPool() {
  const preferredTerms = allTerms.filter((term) => examProbableSet.has(term.english));

  if (preferredTerms.length >= 25) {
    return preferredTerms.slice(0, 25);
  }

  const extraTerms = shuffleArray(
    allTerms.filter((term) => !examProbableSet.has(term.english))
  ).slice(0, 25 - preferredTerms.length);

  return [...preferredTerms, ...extraTerms];
}

function resolveQuestionMode(selectedMode) {
  if (selectedMode !== "mixed") {
    return selectedMode;
  }

  const randomIndex = Math.floor(Math.random() * mixedModes.length);
  return mixedModes[randomIndex];
}

function buildQuestion(term, mode) {
  switch (mode) {
    case "en_es":
      return {
        title: "¿Cómo se dice en español?",
        prompt: term.english,
        answer: term.spanish,
        optionField: "spanish",
      };
    case "es_en":
      return {
        title: "¿Cómo se dice en inglés?",
        prompt: term.spanish,
        answer: term.english,
        optionField: "english",
      };
    case "meaning_en":
      return {
        title: "¿Qué palabra en inglés coincide con este significado?",
        prompt: term.meaning,
        answer: term.english,
        optionField: "english",
      };
    case "en_meaning":
      return {
        title: "¿Cuál es el significado correcto?",
        prompt: term.english,
        answer: term.meaning,
        optionField: "meaning",
      };
    default:
      return {
        title: "¿Cómo se dice en español?",
        prompt: term.english,
        answer: term.spanish,
        optionField: "spanish",
      };
  }
}

function buildOptions(term, question) {
  const options = new Set([question.answer]);

  const primaryPool = currentPool.length >= 4 ? currentPool : allTerms;
  const firstPass = shuffleArray(
    primaryPool
      .filter(
        (item) =>
          !(
            item.english === term.english &&
            item.spanish === term.spanish &&
            item.meaning === term.meaning
          )
      )
      .map((item) => item[question.optionField])
  );

  firstPass.forEach((candidate) => {
    if (options.size < 4) {
      options.add(candidate);
    }
  });

  if (options.size < 4) {
    const backup = shuffleArray(allTerms.map((item) => item[question.optionField]));
    backup.forEach((candidate) => {
      if (options.size < 4) {
        options.add(candidate);
      }
    });
  }

  return shuffleArray([...options].slice(0, 4));
}

